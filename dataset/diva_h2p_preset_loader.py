"""Diva preset loader for u-he's own installed ``.h2p`` preset library.

The second Diva human-preset source, alongside :mod:`dataset.diva_preset_loader`'s Flow
Synthesizer ``diva_raw`` collection. Where ``diva_raw`` realizes only 58 of the 237
D-DIVA-SUBSET parameters -- it was itself generated by varying 64 continuous parameters off
one fixed base patch -- this source is real, hand-made presets spanning the whole space
(D-DIVA-START amendment, 2026-08-30, ``docs/DECISIONS.md``).

``config.DIVA_PRESETS_PATH`` points at Diva's local preset library (factory + ``THIRD PARTY``,
1432 ``.h2p`` files, per the user's call to use both). Parsing and parameter decoding live in
:mod:`synth.diva.patch`; this module only walks the directory and turns each file into a
:class:`~dataset.preset_loader_common.LoadedPreset`, mirroring
:class:`dataset.diva_preset_loader.DivaPresetLoader`'s shape closely enough that the two are
interchangeable behind ``--preset-format`` on ``scripts/build_dataset.py``.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import List, Optional

from synth.diva.patch import parse_h2p, patch_parameters
from synth.parameter_space import ParameterSpace
from .preset_loader_common import LoadedPreset, PresetSplit, deduplicate_presets, split_presets


class DivaH2pPresetLoader:
    """Load, deduplicate and split Diva's installed ``.h2p`` preset library.

    Args:
        parameter_space: the estimated subset; presets are projected onto it for
            deduplication (so dedup sees what actually gets rendered).
        test_fraction: share of surviving presets held out for the test set
            (default 0.0 -- all presets go to train).
        split_seed: seed for the preset-level train/test shuffle.
        dedup_threshold: max-norm distance between projected ML vectors below
            which two presets are duplicates.
    """

    def __init__(
        self,
        parameter_space: ParameterSpace,
        test_fraction: float = 0.0,
        split_seed: int = 0,
        dedup_threshold: float = 1e-3,
    ):
        if not 0.0 <= test_fraction <= 1.0:
            raise ValueError(f"test_fraction must be in [0, 1], got {test_fraction}.")
        self._parameter_space = parameter_space
        self._test_fraction = float(test_fraction)
        self._split_seed = int(split_seed)
        self._dedup_threshold = float(dedup_threshold)

    def load(
        self, source_path: str, limit: Optional[int] = None, show_progress: bool = False
    ) -> PresetSplit:
        """Load every ``.h2p`` preset under ``source_path``, deduplicate, and split.

        Args:
            source_path: a directory recursively searched for ``*.h2p`` files (the shape of
                ``config.DIVA_PRESETS_PATH`` -- factory presets in their category
                subdirectories, ``THIRD PARTY`` in its own).
            limit: cap on the number of presets read, in sorted-path order; ``None`` loads
                all of them. Deduplication and the split then run over the capped set.
            show_progress: draw a tqdm bar for the (slow, O(n^2)) deduplication scan.
        """
        presets = self._load_presets(source_path, limit)
        kept = deduplicate_presets(
            presets, self._parameter_space, self._dedup_threshold, show_progress=show_progress
        )
        return split_presets(kept, self._test_fraction, self._split_seed)

    def _load_presets(self, source_path: str, limit: Optional[int]) -> List[LoadedPreset]:
        if not os.path.isdir(source_path):
            raise FileNotFoundError(f"{source_path} is not a directory.")
        paths = sorted(Path(source_path).rglob("*.h2p"))
        if limit is not None:
            paths = paths[: int(limit)]
        presets: List[LoadedPreset] = []
        for voice_index, path in enumerate(paths):
            parsed = parse_h2p(str(path))
            params = patch_parameters(parsed)
            self._check_subset_coverage(params, str(path))
            presets.append(LoadedPreset(
                params=params,
                source_file=str(path.relative_to(source_path)),
                voice_index=voice_index,
                voice_name=path.stem,
            ))
        if not presets:
            raise RuntimeError(f"No .h2p presets found under {source_path}.")
        return presets

    # -- name-based adapter (D-NAMING) ---------------------------------------
    def _check_subset_coverage(self, params: dict, source_file: str) -> None:
        """Mirrors DivaPresetLoader._check_subset_coverage: fail loudly if a preset does not
        name every estimated-subset parameter, rather than silently dropping any."""
        missing = [name for name in self._parameter_space.names if name not in params]
        if missing:
            raise RuntimeError(
                f"Subset parameter names not present in {source_file}: {missing}. "
                "synth/diva/h2p_param_map.py may be stale for this preset."
            )
